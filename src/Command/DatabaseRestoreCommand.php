<?php

declare(strict_types=1);

namespace App\Command;

use App\Database\BackupManager;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

#[AsCommand(name: 'app:database:restore', description: 'Restore a portable backup to an EMPTY database selected by DATABASE_URL. Never overwrite existing data.')]
final class DatabaseRestoreCommand extends Command
{
    public function __construct(private BackupManager $backup)
    {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this->addArgument('file', InputArgument::REQUIRED, 'A trusted SQL backup generated by app:database:backup.');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $counts = $this->backup->restore($input->getArgument('file'));
        (new SymfonyStyle($input, $output))->success(sprintf('Restored %d tables and %d records. Run app:database:check next.', count($counts), array_sum($counts)));

        return Command::SUCCESS;
    }
}
